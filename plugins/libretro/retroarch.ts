// The sandbox ships source, not the generated treaty's runtime enums.
type LaunchOutput = Omit<PluginLaunchOutput, "saveLocations" | "files"> & {
  files: NonNullable<PluginLaunchOutput["files"]>
  saveLocations: (Omit<SaveLocation, "kind"> & { kind: `${SaveKind}` })[]
}

const jsonType = { Boolean: "boolean", Number: "number", String: "string" }

function unsupported(key: string, value: LaunchSettingValue): string | undefined {
  const expected = keys[key]
  if (expected === undefined || reservedKeys.includes(key))
    return `RetroArch ${version} does not accept ${key} from Korri, so it is not applied`
  if (typeof value !== jsonType[expected])
    return `RetroArch ${version} reads ${key} as ${jsonType[expected]}, not ${typeof value}`
  return undefined
}

// Legacy setting-policy.ts credential keys plus the approved kiosk protections.
const reservedKeys = [
  "cheevos_password",
  "cheevos_token",
  "network_cmd_password",
  "network_cmd_enable",
  "network_cmd_port",
  "netplay_password",
  "netplay_ip_port",
  "netplay_public_announce",
  "netplay_nat_traversal",
  "netplay_use_mitm_server",
  "netplay_spectate_password",
  "kiosk_mode_enable",
  "config_save_on_exit",
  "menu_driver",
]

// config_file_extract_value in the pinned libretro-common/file/config_file.c
// stops at the next quote; it never decodes JSON escapes. Keep native bytes.
function quoteSetting(key: string, value: string): string {
  if (!/[\0\r\n\uD800-\uDFFF]/u.test(value)) {
    if (!value.includes('"')) return `"${value}"`
    // The native unquoted branch accepts printable ASCII up to whitespace.
    // Its comment scanner protects '#' only inside the first quote pair.
    const firstQuote = value.indexOf('"')
    const nextQuote = value.indexOf('"', firstQuote + 1)
    const comment = value.indexOf("#")
    if (
      firstQuote > 0 &&
      /^[\x21-\x7e]+$/.test(value) &&
      (comment < 0 || (firstQuote < comment && nextQuote > comment))
    )
      return value
  }
  // Never put a setting value (which may be private) in the diagnostic.
  throw new Error(`Unsupported RetroArch string setting: ${key}`)
}

type RunnerDeclarations = Record<string, object & { layouts?: object }>

function prepareLaunch(input: PluginLaunchInput, runners: RunnerDeclarations): LaunchOutput {
  const root = input.accountRoot
  const saveRoot = input.saveRoot
  const isMelonds = input.runnerId === "@korri:melonds/melonds"
  if (!input.corePath) throw new Error("RetroArch runner requires a core path")
  const corePath = input.corePath
  // Provider-ref routes carry no file. RetroArch always loads one.
  if (!input.contentPath) throw new Error("RetroArch runner requires a content file")
  const contentPath = input.contentPath
  const states = `${saveRoot}/states/${input.runnerId}`
  const saveDirectories = {
    savefile_directory: `${saveRoot}/saves`,
    savestate_directory: states,
    screenshot_directory: `${saveRoot}/screenshots`,
  }
  const configPath = `${root}/retroarch.cfg`
  const config = input.overrides?.config
  if (config?.replace !== undefined) {
    throw new Error("RetroArch overrides.config does not support replace; use prepend/append")
  }
  // Preserve intended legacy precedence; native duplicate lookup is first-wins.
  const raw = [config?.prepend, config?.append].filter(text => text !== undefined).join("\n")
  const lines: string[] = []
  for (const rawLine of raw.split("\n")) {
    const line = rawLine.trim()
    if (line === "" || line.startsWith("#")) continue
    const separator = line.indexOf("=")
    const key = line.slice(0, separator).trim()
    if (separator < 0 || !/^[A-Za-z0-9_]+$/.test(key)) {
      throw new Error("Invalid RetroArch overrides.config assignment")
    }
    if (reservedKeys.includes(key))
      throw new Error(`Reserved RetroArch overrides.config key: ${key}`)
    // RetroArch requires whitespace before the separator even though this
    // input contract accepts compact assignments. Preserve native value bytes.
    lines.push(`${key} = ${line.slice(separator + 1).trimStart()}`)
  }
  const policy = acceptedPolicy(input.overrides?.settings ?? {})
  // Evidence belongs to the selected frontend. Never emit an unverified pair.
  const typed = renderRetroArchSettings(policy)
    .filter(([key, value]) => unsupported(key, value) === undefined)
    .map(([key, value]) => {
      const serialized =
        typeof value === "number" ? String(value) : quoteSetting(key, String(value))
      return `${key} = ${serialized}`
    })
  const baseline = `# generated by Korri
system_directory = ${quoteSetting("system_directory", `${root}/system`)}
savefile_directory = ${quoteSetting("savefile_directory", saveDirectories.savefile_directory)}
savestate_directory = ${quoteSetting("savestate_directory", saveDirectories.savestate_directory)}
screenshot_directory = ${quoteSetting("screenshot_directory", saveDirectories.screenshot_directory)}

input_driver = "udev"
input_joypad_driver = "udev"
joypad_autoconfig_dir = ${quoteSetting("joypad_autoconfig_dir", input.files.autoconfig)}
${input.files["core-info"] === undefined ? "" : `libretro_directory = ${quoteSetting("libretro_directory", corePath.slice(0, corePath.lastIndexOf("/")))}\nlibretro_info_path = ${quoteSetting("libretro_info_path", input.files["core-info"])}\n`}input_autodetect_enable = "true"
input_max_users = "4"
input_player1_joypad_index = "0"
# Korri inputd routes every controller to a persistent seat pad. udev lists
# them in sysfs-name order (input10 before input8), so default order can put
# Seat P3 on player 1. Preferred reservation (1) matches each seat by name and
# keeps the default order on hosts without seat pads.
input_player1_device_reservation_type = "1"
input_player1_reserved_device = "Korri Seat P1"
input_player2_device_reservation_type = "1"
input_player2_reserved_device = "Korri Seat P2"
input_player3_device_reservation_type = "1"
input_player3_reserved_device = "Korri Seat P3"
input_player4_device_reservation_type = "1"
input_player4_reserved_device = "Korri Seat P4"
input_player1_analog_dpad_mode = "1"
# RetroArch value 2 is L3 + R3. Guide remains exclusive to Korri.
input_menu_toggle_gamepad_combo = "2"
# No RetroArch quit combo (1.22.2 INPUT_COMBO_NONE = 0). Korri inputd owns the
# global kill chord: hold L1 + R1 + Start + Select. A RetroArch Start + Select
# combo would quit first, because Start + Select is part of that chord.
input_quit_gamepad_combo = "0"
quit_press_twice = "false"

kiosk_mode_enable = "true"
menu_driver = "null"
network_cmd_enable = "true"
network_cmd_port = "55355"
# Netplay travels only through korrid's federation forward, including when
# hosting starts during play. Never announce to a lobby or ask a router to map it.
netplay_ip_port = "55435"
netplay_public_announce = "false"
netplay_nat_traversal = "false"
netplay_use_mitm_server = "false"
input_overlay_enable = "false"
# Preserve legacy launch-spec: PNG cartridges belong to the selected core,
# not RetroArch's built-in image viewer.
builtin_imageviewer_enable = "false"
video_fullscreen = "true"
quit_on_close_content = "true"
config_save_on_exit = "false"
pause_nonactive = "true"
autosave_interval = "10"
savestate_auto_save = "true"
savestate_auto_load = "true"
video_driver = "gl"
# Under Gamescope, X11 (Xwayland) shows the game 1:1; RetroArch's Wayland context gets a rescaled surface.
video_context_driver = "x"`
  // Emit exactly one assignment per key. Replacing its original slot keeps
  // baseline comments intact without relying on native duplicate ordering.
  const positions = new Map<string, number>()
  const merged: string[] = []
  for (const line of [...baseline.split("\n"), ...typed, ...lines]) {
    if (line.trim() === "" || line.trimStart().startsWith("#")) {
      merged.push(line)
      continue
    }
    const key = line.slice(0, line.indexOf("=")).trim()
    const position = positions.get(key)
    if (position === undefined) {
      positions.set(key, merged.length)
      merged.push(line)
    } else {
      merged[position] = line
    }
  }
  // Save declarations must match the native folders. melonDS also needs
  // compositor pointer coordinates: the game cannot read physical touch evdev.
  // This rendered cfg is launch-owned and config_save_on_exit stays false;
  // never change the person's policy or the shared-seat joypad driver.
  const managed = { ...saveDirectories, ...(isMelonds ? { input_driver: "x" } : {}) }
  for (const [key, value] of Object.entries(managed)) {
    const position = positions.get(key)
    if (position === undefined) throw new Error(`Missing managed RetroArch baseline key: ${key}`)
    merged[position] = `${key} = ${quoteSetting(key, value)}`
  }
  const files: NonNullable<LaunchOutput["files"]> = []
  const env: Record<string, string> = {}
  let overlay = ""
  if (input.layout !== undefined) {
    const runner = runners[input.runnerId.slice(input.runnerId.lastIndexOf("/") + 1)]
    if (!runner?.layouts || !Object.hasOwn(runner.layouts, input.layout))
      throw new Error("Unsupported runner layout")
    overlay = `melonds_screen_layout = ${quoteSetting("melonds_screen_layout", input.layout)}\nmelonds_screen_gap = "0"\n`
  }
  // Absolute pointer input must not inherit a saved Mouse/Joystick mode.
  // The core's default single-threaded renderer cannot hold 59.9 fps on the
  // RG DS (RK3568, 1.992 GHz A55): 45 fps with GL output, 62 fps threaded (#340).
  if (isMelonds) overlay += 'melonds_threaded_renderer = "enabled"\nmelonds_touch_mode = "Touch"\n'
  if (overlay !== "") {
    const optionsPath = `${root}/melonds-layout.opt`
    // The patched frontend applies this in memory AFTER native source
    // selection. No routing settings change, and no overlay value is saved.
    files.push({ path: optionsPath, content: overlay })
    env.KORRI_RETROARCH_CORE_OPTIONS_OVERLAY = optionsPath
  }
  const content = `${merged.join("\n")}\n`
  return {
    command: input.program,
    args: [
      ...(policy.logging?.level === "verbose" ? ["-v"] : []),
      "--config",
      configPath,
      ...(input.netplay?.role === "client"
        ? ["--connect", input.netplay.address, "--port", String(input.netplay.port)]
        : []),
      ...(input.netplay ? ["--appendconfig", input.netplay.passwordConfig] : []),
      "-L",
      corePath,
      contentPath,
    ],
    directories: [`${root}/system`, `${saveRoot}/saves`, states, `${saveRoot}/screenshots`],
    saveLocations: [
      { key: "saves", kind: "save", path: `${saveRoot}/saves` },
      { key: "states", kind: "savestate", path: `${saveRoot}/states` },
      { key: "screenshots", kind: "screenshot", path: `${saveRoot}/screenshots` },
    ],
    files: [{ path: configPath, content }, ...files],
    env,
    envUnset: [],
  }
}

function objectAt(path: readonly string[], value: unknown): unknown {
  return path.reduceRight<unknown>((child, key) => ({ [key]: child }), value)
}

function evidenceDiagnostics(
  values: unknown,
  schema: SettingSchema = RetroArchPolicy,
  path: string[] = [],
): Diagnostic[] {
  if (schema.type === "object") {
    if (!isRecord(values)) return [] // shape errors are already reported
    return Object.entries(values).flatMap(([key, value]) => {
      const child = Object.hasOwn(schema.properties ?? {}, key)
        ? schema.properties?.[key]
        : Object.entries(schema.patternProperties ?? {}).find(([pattern]) =>
            new RegExp(pattern).test(key),
          )?.[1]
      return child ? evidenceDiagnostics(value, child, [...path, key]) : []
    })
  }
  if (validatePolicy(values, schema, path).length) return []
  // This partial policy comes from a validated schema leaf. The renderer does
  // not require its width/height mate; pair validation happens on the tree.
  const policy = objectAt(path, values) as RetroArchPolicy
  const pairs = renderRetroArchSettings(policy, false)
  return pairs.flatMap(([key, value]): Diagnostic[] => {
    const message = unsupported(key, value)
    if (message) return [{ code: "setting-unverified", severity: "error", path, message }]
    if (typeof value === "string") {
      try {
        quoteSetting(key, value)
      } catch {
        return [
          {
            code: "setting-value",
            severity: "error",
            path,
            message: `Unsupported RetroArch string setting: ${key}`,
          },
        ]
      }
    }
    return []
  })
}

function describeSettings(_input: { id: string }) {
  return {
    schema: {
      $schema: "https://json-schema.org/draft/2020-12/schema",
      ...titledSchema(RetroArchPolicy),
    },
    revision: version,
  }
}

function validateSettings(input: { values?: unknown; revision?: string }) {
  const values = input.values === undefined ? {} : input.values
  const diagnostics: Diagnostic[] = [...validatePolicy(values), ...evidenceDiagnostics(values)]
  if (input.revision !== undefined && input.revision !== version)
    diagnostics.unshift({
      code: "settings-revision",
      severity: "info",
      message: `These values were chosen for RetroArch ${input.revision}; this build is ${version}`,
    })
  return { valid: !diagnostics.some(item => item.severity === "error"), diagnostics }
}

function acceptedPolicy(values: unknown): RetroArchPolicy {
  // Defence in depth for direct callers. Korrid normally removes error paths
  // before launch.prepare. Work on a copy; never rewrite authored values.
  let copy: unknown = JSON.parse(JSON.stringify(values))
  for (;;) {
    const diagnostics = validateSettings({ values: copy }).diagnostics.filter(
      item => item.severity === "error",
    )
    if (!diagnostics.length) return decodeRetroArchPolicy(copy)
    for (const diagnostic of diagnostics) {
      const path = diagnostic.path ?? []
      if (!path.length) {
        copy = {}
        continue
      }
      let parent = copy
      for (const key of path.slice(0, -1)) parent = isRecord(parent) ? parent[key] : undefined
      if (isRecord(parent)) delete parent[path[path.length - 1]]
    }
  }
}

// The host names the operation it wants; every runner answers through the
// same map, so a new operation adds a key rather than a new export contract.
export function createHandlers(runners: RunnerDeclarations) {
  return {
    "launch.prepare": (input: PluginLaunchInput) => prepareLaunch(input, runners),
    "settings.describe": describeSettings,
    "settings.validate": validateSettings,
  }
}
